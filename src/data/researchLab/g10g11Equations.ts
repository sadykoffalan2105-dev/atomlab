/** Учебные уравнения 10–11 классов (Kimyo) — для конструктора в 3D-студии. */

export type GradeEq = {
  id: string
  grade: 'g10' | 'g11'
  topicRu: string
  topicEn: string
  topicUz: string
  left: readonly string[]
  right: readonly string[]
  displayRu: string
  hintRu: string
  hintEn: string
  hintUz: string
}

function eq(
  partial: Omit<GradeEq, 'topicEn' | 'topicUz' | 'hintEn' | 'hintUz'> & {
    topicEn?: string
    topicUz?: string
    hintEn?: string
    hintUz?: string
  },
): GradeEq {
  return {
    topicEn: partial.topicEn ?? partial.topicRu,
    topicUz: partial.topicUz ?? partial.topicRu,
    hintEn: partial.hintEn ?? partial.hintRu,
    hintUz: partial.hintUz ?? partial.hintRu,
    ...partial,
  }
}

