export function equationsByGrade(grade: 'g10' | 'g11' | 'all'): GradeEq[] {
  if (grade === 'all') return [...G10_G11_EDU_EQUATIONS]
  return G10_G11_EDU_EQUATIONS.filter((e) => e.grade === grade)
}

export function normalizeTokenBag(tokens: readonly string[]): string {
  return [...tokens].map((t) => t.trim()).filter(Boolean).sort().join('|')
}

export function equationSidesMatch(
  left: readonly string[],
  right: readonly string[],
  target: GradeEq,
): boolean {
  return (
    normalizeTokenBag(left) === normalizeTokenBag(target.left) &&
    normalizeTokenBag(right) === normalizeTokenBag(target.right)
  )
}
