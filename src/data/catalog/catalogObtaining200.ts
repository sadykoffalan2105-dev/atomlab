const CIRCLED = ['①', '②', '③', '④', '⑤', '⑥'] as const

/** Выверенные этапы получения (null — у вещества остаются прежние данные). */
export function catalogObtainingSteps(id: string): { steps: ObtainingStepRu[]; recipeRu: string } | null {
  const rows = T[id]
  if (!rows?.length) return null
  const steps = rows.map(([equation, note], i): ObtainingStepRu => (note ? { step: i + 1, equation, note } : { step: i + 1, equation }))
  const recipeRu =
    steps.length === 1
      ? steps[0]!.note
        ? `${steps[0]!.equation} — ${steps[0]!.note}`
        : steps[0]!.equation
      : steps.map((s, i) => `${CIRCLED[i] ?? `${s.step}.`} ${s.equation}${s.note ? ` (${s.note})` : ''}`).join('\n')
  return { steps, recipeRu }
}

