/**
 * Карточки школьных объяснений «что / почему / формула / пример / проверка».
 *
 * Зачем они нужны. Локальный составитель ответа (brain/dualMode/localAnswerComposer)
 * умеет только ИЗВЛЕКАТЬ фразы из учебника: на вопрос «почему молекула воды уголковая»
 * в шардах учебника подходящей фразы просто нет, и ответ уходит мимо вопроса.
 * Карточка держит готовые смысловые слоты, поэтому учитель отвечает полно и по делу —
 * без сети, ключей и выдумок.
 *
 * Данные — программа 7–9 класса (Kimyo 7–9). Формулы пишем так же, как в учебнике
 * (нижние индексы ₂, стрелка →) — озвучка разбирает их в learnSpeechText.
 */

export type ExplainerKind = 'what' | 'why' | 'how' | 'compare' | 'example'

/** Языковой набор слотов карточки (ru — обязательный, en/uz — по мере перевода). */
export interface ExplainerCardText {
  /** Что это / что происходит — одна ясная фраза. */
  what: string
  /** Почему так — на уровне частиц. */
  why?: string
  /** Формула, уравнение или расчётное соотношение. */
  formula?: string
  /** Школьный пример (вещество, опыт, случай из жизни). */
  example?: string
  /** Типичная ошибка ученика («а вот так думать нельзя»). */
  misconception?: string
  /** Бытовая аналогия для «объясни проще». */
  simple?: string
  /** Наводка, если ученик сказал «не знаю». */
  hint?: string
  /** Короткий вопрос ученику в конце ответа. */
  check: string
}

export interface ExplainerCard extends ExplainerCardText {
  id: string
  grade: 7 | 8 | 9
  /** Вопросы-триггеры (ru): совпадение по основам слов, а не по строке. */
  terms: string[]
  /** На какие виды вопросов карточка отвечает. */
  kinds: ExplainerKind[]
  /** Что показать в лаборатории: уравнение для «/?reactor=1&eq=…» и что там будет видно. */
  lab?: { eq: string; see: string }
  /** Перевод слотов и триггеров. */
  en?: ExplainerCardText & { terms: string[] }
  uz?: ExplainerCardText & { terms: string[] }
}

