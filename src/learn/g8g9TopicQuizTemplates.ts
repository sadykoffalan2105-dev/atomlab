/** Шаблоны тестов по главам учебников Kimyo 8 и 9 класс. */
export type QuizTemplate = {
  templateKey: string
  question: string
  choices: [string, string, string, string]
  correctIndex: 0 | 1 | 2 | 3
  explanation?: string
}

function mk(
  templateKey: string,
  question: string,
  correct: string,
  pool: string[],
  explanation?: string,
): QuizTemplate {
  return {
    templateKey,
    question,
    choices: [correct, pool[0] ?? '—', pool[1] ?? '—', pool[2] ?? '—'],
    correctIndex: 0,
    explanation,
  }
}

