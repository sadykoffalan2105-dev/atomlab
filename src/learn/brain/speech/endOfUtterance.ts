/**
 * Умный конец фразы: сколько ЕЩЁ подождать тишины, прежде чем считать реплику законченной.
 *
 * Детектор конца реплики (TurnEndDetector) ждёт базовую паузу (финал STT + ~220 мс или
 * ~450 мс тишины по VAD). Этого мало, когда ученик думает посреди фразы: «что такое… оксиды»,
 * «а если взять, например…», «масса двадцать… восемь грамм». Здесь — добавка к паузе по тексту:
 *
 *  • висящий хвост (союз, предлог, «например», «потому что», вопросительное слово, «такое»,
 *    незаконченное число или буква формулы, слово-паразит «э-э / ну») — ждём дольше (+1100 мс);
 *  • короткая реплика из 1–2 слов, не команда — может продолжить (+600 мс);
 *  • законченная фраза из ≥ 3 слов — небольшой запас (+250 мс);
 *  • команда («стоп», «да», «нет», «дальше», «повтори») и «?» в конце — без добавки.
 *
 * Итог от реального конца речи (VAD держит ещё ~200 мс): законченная ≈ 0,7–0,9 с,
 * короткая ≈ 1,0–1,25 с, висящий хвост ≈ 1,5–1,75 с. Длинные вопросы (15–25 слов)
 * не режутся: каждая новая порция текста перезапускает ожидание.
 *
 * Чистый модуль, без DOM (scripts/test-voice-recognition.mts).
 */

export type UtteranceEnding = 'command' | 'question' | 'complete' | 'short' | 'dangling' | 'empty'

export interface UtteranceHold {
  ending: UtteranceEnding
  /** Добавка к базовой паузе конца реплики, мс. */
  holdMs: number
}

/** Добавки к паузе (мс). */
export const HOLD_MS: Readonly<Record<UtteranceEnding, number>> = {
  empty: 0,
  command: 0,
  question: 0,
  complete: 250,
  short: 600,
  dangling: 1100,
}

function words(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^\p{L}\p{N}'’ʻ]+/u)
    .filter(Boolean)
}

