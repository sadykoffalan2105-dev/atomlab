/** Общие → мега-школа → точечная химия (последнее побеждает при конфликте). */
const MERGED_STRESS_RU: Record<string, string> = {
  ...COMMON_STRESS_RU,
  ...SCHOOL_CHEMISTRY_STRESS_MEGA,
  ...CHEMISTRY_STRESS_RU,
}

const SORTED_KEYS = Object.keys(MERGED_STRESS_RU).sort((a, b) => b.length - a.length)

function stripExistingStressMarks(text: string): string {
  return text.replace(/\u0301/g, '')
}

/** Подставляет ударения в текст перед озвучкой. */
export function applyRussianStressMarks(text: string): string {
  let out = stripExistingStressMarks(text)
  for (const key of SORTED_KEYS) {
    const stressed = MERGED_STRESS_RU[key]!
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const re = new RegExp(`(?<![\\p{L}])${escaped}(?![\\p{L}])`, 'giu')
    out = out.replace(re, (match) => {
      if (match === match.toUpperCase()) return stressed.toUpperCase()
      if (match[0] === match[0]?.toUpperCase()) {
        return stressed.charAt(0).toUpperCase() + stressed.slice(1)
      }
      return stressed
    })
  }
  return out
}
