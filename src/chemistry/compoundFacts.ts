function pick<T>(id: string, variants: readonly T[]): T {
  const i = Math.abs(hash32(id)) % variants.length
  return variants[i]!
}

function metalFromSaltId(id: string): string | null {
  const m = id.match(/^salt_([a-z0-9]+?)_/)
  if (!m) return null
  const map: Record<string, string> = {
    na: 'натрия',
    k: 'калия',
    li: 'лития',
    cs: 'цезия',
    ag: 'серебра',
    mg: 'магния',
    ca: 'кальция',
    ba: 'бария',
    sr: 'стронция',
    zn: 'цинка',
    cu: 'меди',
    fe2: 'железа',
    fe3: 'железа',
    al: 'алюминия',
    pb: 'свинца',
    sn: 'олова',
    mn: 'марганца',
    ni: 'никеля',
    cobalt: 'кобальта',
    cr: 'хрома',
    nh4: 'аммония',
  }
  return map[m[1]!] ?? null
}

function anionKeyFromSaltId(id: string): string | null {
  const m = id.match(/^salt_[a-z0-9]+_(.+)$/)
  if (!m) return null
  return m[1]!.replace(/3_po4$/, 'po4').replace(/^(\w+)$/, (s) => s.toUpperCase())
}

