function categoryFallback(p: RawCompoundDef): CompoundFactsRu {
  const f = p.formulaUnicode
  const cat: Record<CompoundCategory, CompoundFactsRu> = {
    oxide: oxideFacts(p),
    acid: acidFacts(p),
    base: baseFacts(p),
    salt: saltFacts(p),
    other: {
      source: 'Минеральное сырьё или синтез в химической промышленности.',
      usage: 'Промышленность, лаборатория, учебные демонстрации.',
      importance: `${f} — вещество школьного курса неорганической химии.`,
    },
  }
  return cat[p.category]
}

/** Полные факты для любого вещества каталога. */
export function resolveCompoundFacts(p: RawCompoundDef): CompoundFactsRu {
  if (p.factsRu) return p.factsRu
  const curated = CURATED[p.id]
  if (curated) return curated
  return categoryFallback(p)
}
