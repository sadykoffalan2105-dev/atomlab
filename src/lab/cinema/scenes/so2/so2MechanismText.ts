/**
 * Тексты урока «S + O₂ → SO₂» — панель шагов.
 *
 * Уровень 8–9 класса (Kimyo): ковалентная полярная связь, общая электронная
 * пара, неподелённая пара и форма молекулы.
 * Правила текста:
 *   • числа справочные (длины и углы — NIST CCCBDB, энтальпии — NIST-JANAF/CRC)
 *     и те же, что нарисованы в сцене;
 *   • всё, что показано схематично (светящиеся электроны, π-облако, одна
 *     молекула вместо моля), так и названо в поле note;
 *   • это DOM-текст: индексы и знаки пишутся настоящими символами (₂, °, Δ, ⇌).
 */

export type So2Locale = 'ru' | 'en' | 'uz'

export type So2StepText = {
  title: string
  /** 2–4 предложения для панели */
  body: string
  /** уравнение стадии */
  equation: string
  /** честная пометка об упрощении */
  note?: string
  /** короткая реплика преподавателя */
  speak: string
}

export type So2EnergyText = {
  title: string
  /** единица у чисел */
  unit: string
  /** подпись под лестницей */
  caption: string
  stages: {
    atomization: string
    dissociation: string
    bonds: string
    total: string
  }
  /** aria-label лестницы; {dH} */
  summary: string
  sources: string
}

export type So2MechanismText = {
  intro: { title: string; speak: string }
  steps: Record<So2StepId, So2StepText>
  legend: {
    electron: string
    orbitalPhase: string
  }
  safety: string
  energy: So2EnergyText
}

