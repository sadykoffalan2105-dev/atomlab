export type H2oLocale = 'ru' | 'en' | 'uz'

export type H2oStepText = {
  title: string
  /** 2–4 предложения для панели */
  body: string
  /** уравнение стадии */
  equation: string
  /** честная пометка об упрощении */
  note?: string
  /** короткая реплика преподавателя */
  speak: string
}

export type H2oEnergyText = {
  title: string
  /** единица у чисел */
  unit: string
  /** подпись под лестницей */
  caption: string
  stages: {
    dissocHH: string
    dissocOO: string
    bond1: string
    bond2: string
    total: string
  }
  /** aria-label лестницы; {dH} */
  summary: string
  sources: string
}

export type H2oMechanismText = {
  intro: { title: string; speak: string }
  steps: Record<H2oStepId, H2oStepText>
  legend: {
    electron: string
    orbitalPhase: string
    water: string
  }
  safety: string
  energy: H2oEnergyText
}

