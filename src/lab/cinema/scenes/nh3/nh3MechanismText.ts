/**
 * Тексты урока «синтез аммиака: N₂ + 3 H₂ ⇌ 2 NH₃» — панель шагов.
 *
 * Уровень 9 класса (Kimyo). Правила текста:
 *   • числа справочные (энергии и длины связей — CRC/NIST, угол и дипольный
 *     момент — NIST CCCBDB, решётка железа — ICSD, условия процесса —
 *     Ullmann's «Ammonia»); они же нарисованы в сцене и на лестнице энергии;
 *   • всё, что показано схематично (π-облака, неподелённая пара, скольжение
 *     атомов по поверхности, фрагмент железа), так и названо в поле note;
 *   • реакция ОБРАТИМАЯ: всюду «⇌», никогда «→»;
 *   • это DOM-текст: индексы и знаки пишутся настоящими символами (₂, ⇌, Δ, °, −).
 */

export type Nh3Locale = 'ru' | 'en' | 'uz'

export type Nh3StepText = {
  title: string
  /** 2–4 предложения для панели */
  body: string
  /** уравнение стадии */
  equation: string
  /** честная пометка об упрощении */
  note?: string
  /** короткая реплика преподавателя */
  speak: string
}

export type Nh3EnergyText = {
  title: string
  /** единица у чисел (лестница построена на ОДНО уравнение, то есть на 2 моль NH₃) */
  unit: string
  /** подпись под лестницей */
  caption: string
  stages: {
    hh: string
    nn: string
    nh: string
    total: string
  }
  /** aria-label лестницы; {dH} */
  summary: string
  sources: string
}

export type Nh3MechanismText = {
  intro: { title: string; speak: string }
  steps: Record<Nh3StepId, Nh3StepText>
  legend: {
    electron: string
    orbitalPhase: string
    vibration: string
  }
  safety: string
  energy: Nh3EnergyText
}

