/**
 * Тексты урока «механизм получения ClO₂» — панель шагов и озвучка.
 *
 * Химия сверена с источниками (см. clo2Steps.ts). Правила текста:
 *   • всё, что предположено, а не наблюдалось, так и называется;
 *   • «электрон перешёл» говорим только в итоговом балансе — по ходу реакции
 *     электроны двигаются парами внутри связей;
 *   • NaCl в растворе — растворённые ионы, не осадок.
 * Это DOM-текст: индексы и заряды пишутся настоящими символами (₂, ⁻, ⁺, δ).
 */

export type Clo2Locale = 'ru' | 'en' | 'uz'

export type Clo2StepText = {
  title: string
  /** 2–4 предложения для панели */
  body: string
  /** уравнение элементарной стадии */
  equation: string
  /** честная пометка об упрощении / степени уверенности */
  note?: string
  /** 1–2 короткие фразы для озвучки (без формул в индексах) */
  speak: string
}

export type Clo2MechanismText = {
  intro: { title: string; speak: string }
  steps: Record<Clo2StepId, Clo2StepText>
  legend: {
    electron: string
    pairArrow: string
    singleArrow: string
    water: string
    /** цвет лепестков орбитали — фаза волновой функции */
    orbitalPhase: string
    /** колебания атомов: частоты настоящие, время замедлено */
    vibration: string
  }
  safety: string
  /** энергетический профиль (Clo2EnergyProfile); шаблоны — с {плейсхолдерами} */
  energy: Clo2EnergyText
  /** счётчик электронов (Clo2ElectronLedger) */
  ledger: Clo2LedgerText
}

export type Clo2EnergyText = {
  title: string
  /** подпись оси энергии */
  axisG: string
  /** подпись оси «координата реакции» */
  axisCoord: string
  /** единица у чисел на графике */
  unit: string
  /** легенда: значение прямо из измерений */
  measured: string
  /** легенда: пересчитано из измерений через модель */
  derived: string
  /** легенда и подпись у ям: уровень не измерен */
  schematic: string
  /** подпись основного пути после развилки: {pct} */
  mainLabel: string
  /** подпись хлоратной ветки: {pct} */
  branchLabel: string
  /** главные оговорки: барьеры кажущиеся, ямы схематичны; {dG}, {dGAlt} */
  caveat: string
  /** две модели происхождения хлората; {ts2}, {tsCl}, {main}, {side} */
  chlorateModels: string
  /** реальное время реакции; {ms} */
  halfLife: string
  sources: string
  /** заголовок раскрывающегося блока «модели и источники» */
  more: string
  /** aria-label графика; {dG}, {ts1}, {ts2}, {main}, {side} */
  summary: string
}

export type Clo2LedgerText = {
  /** «валентных e⁻» */
  valence: string
  /** всплывающая подсказка к счётчику */
  valenceHint: string
  /** подпись бейджа орбитали */
  orbital: string
  /** всплывающая подсказка к бейджу */
  orbitalHint: string
  /** aria-label строки; {n}, {breakdown}, {occ} */
  aria: string
}

