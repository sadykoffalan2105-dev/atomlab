export type NaclLocale = 'ru' | 'en' | 'uz'

export type NaclStepText = {
  title: string
  /** 2–4 предложения для панели */
  body: string
  /** уравнение стадии */
  equation: string
  /** честная пометка об упрощении */
  note?: string
  /** короткая реплика преподавателя */
  speak: string
}

export type NaclEnergyText = {
  title: string
  /** единица у чисел */
  unit: string
  /** подпись под лестницей */
  caption: string
  stages: {
    sublimation: string
    ionization: string
    dissociation: string
    affinity: string
    lattice: string
    total: string
  }
  /** aria-label лестницы; {dH} */
  summary: string
  sources: string
}

