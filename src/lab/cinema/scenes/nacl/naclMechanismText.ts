/**
 * Тексты урока «ионная связь: 2 Na + Cl₂ → 2 NaCl» — панель шагов.
 *
 * Уровень 7–8 класса (Kimyo): атом отдаёт / принимает электрон, ионы, решётка.
 * Правила текста:
 *   • числа справочные (радиусы Shannon/CRC, энтальпии NIST-JANAF/CRC,
 *     параметры ячейки Wyckoff/ICSD) — они же нарисованы в сцене;
 *   • всё, что показано схематично (свечение оболочки, «полёт» электрона,
 *     фрагмент из 64 ионов), так и названо в поле note;
 *   • это DOM-текст: индексы и заряды пишутся настоящими символами (₂, ⁻, ⁺, Δ).
 */

export type NaclLocale = 'ru' | 'en' | 'uz'

export type NaclStepText = {
  title: string
  /** 2–4 предложения для панели */
  body: string
  /** уравнение стадии */
  equation: string
  /** честная пометка об упрощении */
  note?: string
  /** короткая реплика преподавателя */
  speak: string
}

export type NaclEnergyText = {
  title: string
  /** единица у чисел */
  unit: string
  /** подпись под лестницей */
  caption: string
  stages: {
    sublimation: string
    ionization: string
    dissociation: string
    affinity: string
    lattice: string
    total: string
  }
  /** aria-label лестницы; {dH} */
  summary: string
  sources: string
}

export type NaclMechanismText = {
  intro: { title: string; speak: string }
  steps: Record<NaclStepId, NaclStepText>
  legend: {
    electron: string
    orbitalPhase: string
  }
  safety: string
  energy: NaclEnergyText
}

