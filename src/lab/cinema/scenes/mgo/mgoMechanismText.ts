/**
 * Тексты урока «горение магния: 2 Mg + O₂ → 2 MgO» — панель шагов.
 *
 * Уровень 7–8 класса (Kimyo): атом отдаёт / принимает электроны, ионы, решётка.
 * Правила текста:
 *   • числа справочные (радиусы Shannon/CRC, энтальпии NIST-JANAF/CRC,
 *     параметры ячейки Wyckoff/ICSD) — они же нарисованы в сцене;
 *   • всё, что показано схематично (свечение оболочки, «полёт» электрона,
 *     фрагмент из 64 ионов), так и названо в поле note;
 *   • это DOM-текст: индексы и заряды пишутся настоящими символами (₂, ²⁻, ²⁺, Δ).
 */

export type MgoLocale = 'ru' | 'en' | 'uz'

export type MgoStepText = {
  title: string
  /** 2–4 предложения для панели */
  body: string
  /** уравнение стадии */
  equation: string
  /** честная пометка об упрощении */
  note?: string
  /** короткая реплика преподавателя */
  speak: string
}

export type MgoEnergyText = {
  title: string
  /** единица у чисел */
  unit: string
  /** подпись под лестницей */
  caption: string
  stages: {
    sublimation: string
    dissociation: string
    ionization1: string
    ionization2: string
    affinity1: string
    affinity2: string
    lattice: string
    total: string
  }
  /** aria-label лестницы; {dH} */
  summary: string
  sources: string
}

export type MgoMechanismText = {
  intro: { title: string; speak: string }
  steps: Record<MgoStepId, MgoStepText>
  legend: {
    electron: string
    orbitalPhase: string
  }
  safety: string
  energy: MgoEnergyText
}

