function buildOutlinePack(): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [key, title] of Object.entries(learnGradesOutlineRu)) {
    if (!key.endsWith('.title') || !/^learn\.g[789]\./.test(key)) continue
    const prefix = key.slice(0, -'.title'.length)
    if (G7_PILOT_PREFIXES.has(prefix)) continue
    const topic = stripSectionTitle(title)
    const c = topicContent(topic)
    Object.assign(
      out,
      buildFullSectionSlides(prefix, topic, c.example, c.q, c.choices, c.correct, c.lab, {
        bullets0: [
          `Параграф: ${topic}`,
          `Интересно: ${c.example.split('.')[0]}.`,
          'Сверьте теорию с 3D-моделью справа',
          'Запомните определение и один пример из жизни',
        ],
        callout0: 'Факт дня: химия вокруг нас — от воздуха до пищи. Обсудите примеры в классе.',
        bullets3: [`Итог: ${topic}`, 'Повторите ключевые термины', 'Проверьте себя вопросом ниже'],
      }),
    )
  }
  return out
}

export const learnOutlineContentRu = buildOutlinePack()
