const TABLES: Record<AppLocale, Record<TTKey, string>> = { ru, uz, en }

export function ttFor(locale: AppLocale) {
  const table = TABLES[locale] ?? ru
  return (key: TTKey, vars?: Record<string, string | number>): string => {
    const raw = table[key] ?? ru[key] ?? key
    return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : raw
  }
}

export function useTT() {
  const { locale } = useLocale()
  const tt = useMemo(() => ttFor(locale), [locale])
  return { locale, tt }
}

