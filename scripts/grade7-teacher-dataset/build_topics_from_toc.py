def slugify(text: str) -> str:
    t = text.lower().strip()
    t = re.sub(r"[^a-zа-яё0-9]+", "-", t, flags=re.I)
    t = re.sub(r"-+", "-", t).strip("-")
    return t[:48] or "section"


def enrich(title: str) -> dict:
    title_l = title.lower()
    base = {
        "key_concepts": [],
        "formulas": [],
        "facts": [f"Тема школьной программы: {title}."],
        "common_mistakes": ["Путает близкие термины по этой теме", "Заучивает без понимания механизма"],
    }
    for pattern, data in ENRICHMENT:
        if re.search(pattern, title_l, flags=re.I):
            for k in ("key_concepts", "formulas", "facts", "common_mistakes"):
                for item in data.get(k, []):
                    if item not in base[k]:
                        base[k].append(item)
    # keep facts short
    base["facts"] = base["facts"][:4]
    base["key_concepts"] = base["key_concepts"][:8] or [title.split()[0]]
    base["common_mistakes"] = base["common_mistakes"][:4]
    base["formulas"] = base["formulas"][:8]
    return base


def skip_title(title: str) -> bool:
    t = title.lower()
    return bool(
        re.search(
            r"повторение|сборник задач|итоговый анализ|лабораторн|практическ|техника безопасности|закрепление главы|задачи и упражнен",
            t,
        )
    )


def build_grade(grade: int) -> dict:
    toc_path = TOC_FILES[grade]
    toc = json.loads(toc_path.read_text(encoding="utf-8"))
    assert isinstance(toc, list)

    by_ch: dict[int, list] = defaultdict(list)
    for row in toc:
        if skip_title(row["titleRu"]):
            continue
        by_ch[int(row["ch"])].append(row)

    topics = []
    for ch in sorted(by_ch):
        title = CHAPTER_TITLES.get(grade, {}).get(ch, f"Глава {ch}")
        subtopics = []
        for row in by_ch[ch]:
            extra = enrich(row["titleRu"])
            subtopics.append(
                {
                    "id": f"c{ch}-s{row['sec']:02d}-{slugify(row['titleRu'])}",
                    "title": row["titleRu"],
                    "kp": row.get("kp"),
                    "page": row.get("page"),
                    **extra,
                }
            )
        if not subtopics:
            continue
        topics.append(
            {
                "id": f"c{ch}-{slugify(title)}",
                "title": title,
                "chapter": ch,
                "subtopics": subtopics,
            }
        )

    return {
        "grade": grade,
        "locale": "ru",
        "title": f"Химия {grade} класс — справочник тем для SFT-датасета ИИ-учителя",
        "source": f"g{grade}BookToc.json (Kimyo / school TOC) + enrichment",
        "system_teacher_persona": (
            f"Ты — опытный учитель химии {grade} класса ATOMLAB. Объясняй точно, по шагам, на уровне {grade} класса. "
            "Не выдумывай факты. Сначала прямой ответ, затем причина, затем пример. "
            "Используй школьную терминологию."
        ),
        "student_profiles": PROFILES,
        "topics": topics,
    }


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for grade in (8, 9, 10, 11):
        data = build_grade(grade)
        out = OUT_DIR / f"grade{grade}.json"
        out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        n_sub = sum(len(t["subtopics"]) for t in data["topics"])
        print(f"grade{grade}: topics={len(data['topics'])} subtopics={n_sub} -> {out}")


if __name__ == "__main__":
    main()
