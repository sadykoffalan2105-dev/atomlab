def gen(curriculum: dict, start: int, total: int) -> list[dict]:
    sections = [(ch, i + 1, kp, title) for ch, items in sorted(curriculum.items()) for i, (kp, title) in enumerate(items)]
    n = len(sections)
    step = max(3, (total - start - 10) // n)
    page = start
    out = []
    for ch, sec, kp, title in sections:
        out.append({"ch": ch, "sec": sec, "kp": kp, "page": page, "titleRu": title, "titleEn": title})
        page = min(page + step, total - 2)
    return out


