const map = {}
for (const r of RAW) {
  const stressed = fromPipe(r)
  const key = r.replace(/\|/g, '')
  map[key] = stressed
}
for (const yo of YO) {
  map[yo] = yo
  const ye = yo.replace(/ё/g, 'е').replace(/Ё/g, 'Е')
  if (ye !== yo) map[ye] = yo
}

const lines = Object.entries(map)
  .sort((a, b) => a[0].localeCompare(b[0], 'ru'))
  .map(([k, v]) => {
    let tpl = ''
    for (const ch of v) {
      tpl += ch === '\u0301' ? '${A}' : ch
    }
    return `  ${JSON.stringify(k)}: \`${tpl}\`,`
  })

const file = `/**
 * Школьный мега-словарь ударений для TTS ИИ-учителя.
 * COMBINING ACUTE (U+0301). Сборка: node scripts/build-russian-stress-mega.mjs
 */
const A = '\\u0301'

export const SCHOOL_CHEMISTRY_STRESS_MEGA: Record<string, string> = {
${lines.join('\n')}
}
`

fs.writeFileSync(OUT, file, 'utf8')
console.log('Wrote', Object.keys(map).length, 'stress entries →', OUT)
