#!/usr/bin/env node
/**
 * Мега-база знаний ИИ-учителя (~100× к ручным packs / плотный индекс).
 * Источники: учебники g7–g9, каталоги тем 7–11, элементы, теория, реакции, FAQ, расчёты.
 *
 * Запуск: npm run build:teacher-knowledge
 * Выход: src/data/teacherKnowledge/megaPack.json (+ megaPackExtra.json при большом объёме)
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const OUT_DIR = path.join(ROOT, 'src', 'data', 'teacherKnowledge')
const OUT_FILE = path.join(OUT_DIR, 'megaPack.json')
const OUT_EXTRA = path.join(OUT_DIR, 'megaPackExtra.json')
/** Цель: ~100× к ~325 hand-chunks → ~30–40k; потолок чтобы не убить бандл. */
const HARD_CAP = 42_000
const PRIMARY_SHARE = 28_000

function readJson(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'))
}

function chunk(id, topic, grades, keywords, ru, en) {
  const kw = [...new Set(keywords.map((k) => String(k).toLowerCase().trim()).filter((k) => k.length >= 2))].slice(
    0,
    14,
  )
  return {
    id,
    topic: String(topic).slice(0, 120),
    grades,
    keywords: kw,
    ru: String(ru).replace(/\s+/g, ' ').trim().slice(0, 720),
    en: String(en || ru)
      .replace(/\s+/g, ' ')
      .trim()
      .slice(0, 280),
  }
}

function splitParagraphs(text, maxLen = 220) {
  const raw = String(text || '')
    .replace(/\r/g, '')
    .split(/\n{2,}|(?<=[.!?…])\s+(?=[А-ЯA-Z«"0-9•–—-])/)
    .map((s) => s.replace(/\s+/g, ' ').trim())
    .filter((s) => s.length >= 36)
  const out = []
  let buf = ''
  for (const p of raw) {
    if ((buf + ' ' + p).trim().length <= maxLen) buf = (buf + ' ' + p).trim()
    else {
      if (buf) out.push(buf)
      if (p.length <= maxLen) buf = p
      else {
        for (let i = 0; i < p.length; i += maxLen) out.push(p.slice(i, i + maxLen))
        buf = ''
      }
    }
  }
  if (buf) out.push(buf)
  return out.length ? out : raw.slice(0, 12)
}

function kwFromText(...parts) {
  const bag = []
  for (const p of parts) {
    const m = String(p || '')
      .toLowerCase()
      .match(/[а-яёa-z0-9-]{4,}/gi)
    if (m) bag.push(...m.slice(0, 8))
  }
  return bag
}

const chunks = []
const seen = new Set()

function push(c) {
  if (!c?.id || !c.ru || seen.has(c.id)) return
  if (chunks.length >= HARD_CAP) return
  seen.add(c.id)
  chunks.push(c)
}

// --- 1) Учебники g7–g9: плотные срезы + педагогические вариации ---
for (const grade of ['g7', 'g8', 'g9']) {
  const gradeNum = Number(grade.slice(1))
  const data = readJson(`src/data/${grade}TextbookKnowledge.json`)
  const sections = data.sections || data
  for (const sec of sections) {
    const topicRu = sec.topicRu || sec.titleRu || sec.topic || 'Тема'
    const topicEn = sec.topicEn || sec.titleEn || topicRu
    const sid = sec.id || `${sec.chapterId}-${sec.sectionId}`
    const baseKw = [
      topicRu,
      ...(sec.keywords || []).slice(0, 16),
      grade,
      sec.chapterId,
      sec.sectionId,
      ...(sec.conceptsRu || []).slice(0, 8),
    ].filter(Boolean)

    const bodies = []
    if (Array.isArray(sec.ragParts)) {
      for (const p of sec.ragParts) {
        if (typeof p === 'string' && p.trim()) bodies.push(p.trim())
        else if (p?.ru) bodies.push(String(p.ru))
        else if (p?.textRu) bodies.push(String(p.textRu))
      }
    }
    if (sec.contentRu) bodies.push(String(sec.contentRu))

    if (Array.isArray(sec.definitionsRu)) {
      sec.definitionsRu.forEach((d, i) => {
        if (!d || String(d).length < 18) return
        const body = String(d).replace(/\s+/g, ' ').trim()
        push(
          chunk(
            `${sid}-def-${i}`,
            `Определение: ${topicRu}`,
            [gradeNum],
            [...baseKw, 'определен', 'что такое'],
            `**${topicRu}** (кл. ${gradeNum}, определение).\n${body}`,
            `Definition (${topicEn}): ${body}`,
          ),
        )
        push(
          chunk(
            `${sid}-def-${i}-ask`,
            `Вопрос: что такое — ${topicRu}`,
            [gradeNum],
            [...baseKw, 'что такое', 'определен', 'сформулир'],
            `**Вопрос ученика:** что такое «${topicRu}»?\n**Ответ:** ${body}`,
            `Q: what is ${topicEn}? A: ${body}`,
          ),
        )
      })
    }

    if (Array.isArray(sec.conceptsRu)) {
      sec.conceptsRu.forEach((c, i) => {
        push(
          chunk(
            `${sid}-concept-${i}`,
            `Понятие: ${c}`,
            [gradeNum],
            [...baseKw, c, 'понятие', 'термин'],
            `**Ключевое понятие (§ ${topicRu}).** ${c}. Класс ${gradeNum}.`,
            `Key concept in ${topicEn}: ${c}.`,
          ),
        )
        push(
          chunk(
            `${sid}-concept-${i}-check`,
            `Проверка: ${c}`,
            [gradeNum],
            [...baseKw, c, 'проверь', 'контроль', 'вопрос'],
            `**Проверь себя (§ ${topicRu}).** Объясни своими словами: что такое «${c}»? Приведи 1 пример.`,
            `Self-check: explain «${c}» with one example.`,
          ),
        )
      })
    }

    const joined = bodies.join('\n\n')
    const parts = splitParagraphs(joined, 160)
    parts.forEach((part, i) => {
      push(
        chunk(
          `${sid}-p-${i}`,
          `${topicRu} (§${i + 1})`,
          [gradeNum],
          [...baseKw, ...kwFromText(part)],
          `**${topicRu}** (класс ${gradeNum}, стр. ${sec.page || '—'}).\n${part}`,
          `${topicEn}: ${part}`,
        ),
      )
      // Педагогические микрокарточки (×4 к плотности RAG)
        if (part.length >= 60 && i < 60) {
          push(
            chunk(
              `${sid}-p-${i}-why`,
              `Почему важно: ${topicRu}`,
              [gradeNum],
              [...baseKw, 'почему', 'зачем', 'важно'],
              `**Зачем это нужно (${topicRu}).** ${part}\nСвяжи с жизнью/опытом одним предложением.`,
              `Why it matters (${topicEn}): ${part}`,
            ),
          )
          push(
            chunk(
              `${sid}-p-${i}-ex`,
              `Пример: ${topicRu}`,
              [gradeNum],
              [...baseKw, 'пример', 'например'],
              `**Пример по теме «${topicRu}».** Опора на текст: ${part}`,
              `Example (${topicEn}): ${part}`,
            ),
          )
          push(
            chunk(
              `${sid}-p-${i}-err`,
              `Ошибка: ${topicRu}`,
              [gradeNum],
              [...baseKw, 'ошибк', 'путают', 'неправильно'],
              `**Типичная ошибка (§ ${topicRu}).** Ученик пропускает условие или путает термины. Верный ориентир: ${part}`,
              `Common slip (${topicEn}): ${part}`,
            ),
          )
          push(
            chunk(
              `${sid}-p-${i}-how`,
              `Как понять: ${topicRu}`,
              [gradeNum],
              [...baseKw, 'как понять', 'объясн', 'простым'],
              `**Простыми словами (§ ${topicRu}).** ${part}`,
              `In plain words (${topicEn}): ${part}`,
            ),
          )
        }
    })

    const remember = sec.rememberRu || ''
    if (remember) {
      push(
        chunk(
          `${sid}-remember`,
          `Запомните: ${topicRu}`,
          [gradeNum],
          [...baseKw, 'запомните', 'итог', 'вывод'],
          `**Краткий итог (${topicRu}).** ${String(remember).replace(/\s+/g, ' ').trim()}`,
          `Key takeaway (${topicEn}): ${String(sec.rememberEn || remember).slice(0, 400)}`,
        ),
      )
    }
  }
}

// --- 2) Каталоги тем 7–11 (SFT topics) → факты / понятия / ошибки / формулы ---
for (const g of [7, 8, 9, 10, 11]) {
  const catalog = readJson(`scripts/grade7-teacher-dataset/topics/grade${g}.json`)
  for (const topic of catalog.topics || []) {
    for (const sub of topic.subtopics || []) {
      const baseId = `mega-cat-g${g}-${topic.id}-${sub.id}`
      const title = sub.title || topic.title
      const baseKw = [title, topic.title, `класс ${g}`, ...(sub.key_concepts || []).slice(0, 8)]

      push(
        chunk(
          `${baseId}-overview`,
          title,
          [g],
          [...baseKw, 'тема', 'обзор'],
          `**${title} (${g} класс).** Раздел «${topic.title}». Ключевые понятия: ${(sub.key_concepts || []).slice(0, 8).join(', ') || '—'}.`,
          `${title} (grade ${g}). Concepts: ${(sub.key_concepts || []).slice(0, 6).join(', ')}.`,
        ),
      )

      ;(sub.key_concepts || []).forEach((c, i) => {
        push(
          chunk(
            `${baseId}-kc-${i}`,
            `Понятие: ${c}`,
            [g],
            [...baseKw, c, 'понятие', 'термин'],
            `**${c}** — ключевое понятие темы «${title}» (${g} кл.). Объясни определение → пример → где применяется.`,
            `Concept «${c}» in «${title}» (grade ${g}).`,
          ),
        )
        push(
          chunk(
            `${baseId}-kc-${i}-teach`,
            `Как объяснить: ${c}`,
            [g],
            [...baseKw, c, 'объясн', 'простым языком'],
            `**Учительский ход — ${c}.** 1) Одно предложение-определение. 2) Бытовой пример. 3) Школьная формула/схема. 4) Типичная путаница. Тема: ${title}.`,
            `Teach «${c}»: definition → example → schema → mistake.`,
          ),
        )
      })

      ;(sub.facts || []).forEach((f, i) => {
        const fact = String(f).trim()
        if (fact.length < 12) return
        push(
          chunk(
            `${baseId}-fact-${i}`,
            `Факт: ${title}`,
            [g],
            [...baseKw, ...kwFromText(fact), 'факт'],
            `**Факт (${title}, ${g} кл.).** ${fact}`,
            `Fact (${title}): ${fact}`,
          ),
        )
        push(
          chunk(
            `${baseId}-fact-${i}-q`,
            `Вопрос по факту: ${title}`,
            [g],
            [...baseKw, 'вопрос', 'проверка', ...kwFromText(fact)],
            `**Вопрос:** опираясь на тему «${title}», объясни: ${fact}\n**Ориентир ответа:** начни с прямого утверждения, затем «почему».`,
            `Prompt: explain this fact: ${fact}`,
          ),
        )
      })

      ;(sub.common_mistakes || []).forEach((m, i) => {
        const mistake = String(m).trim()
        if (!mistake) return
        push(
          chunk(
            `${baseId}-misc-${i}`,
            `Ошибка: ${title}`,
            [g],
            [...baseKw, 'ошибк', 'путают', 'заблужден', ...kwFromText(mistake)],
            `**Типичная ошибка — ${title} (${g} кл.).** ${mistake}\nИсправь мягко: сначала верный факт, потом почему так думают.`,
            `Misconception (${title}): ${mistake}`,
          ),
        )
      })

      ;(sub.formulas || []).forEach((f, i) => {
        const formula = String(f).trim()
        if (!formula) return
        push(
          chunk(
            `${baseId}-fml-${i}`,
            `Формула: ${title}`,
            [g],
            [...baseKw, 'формул', 'расчёт', formula],
            `**Формула / соотношение (${title}, ${g} кл.).** \`${formula}\`\nПодпиши величины и единицы; скажи, когда применять.`,
            `Formula (${title}): ${formula}`,
          ),
        )
      })

      push(
        chunk(
          `${baseId}-drill`,
          `Мини-проверка: ${title}`,
          [g],
          [...baseKw, 'проверь', 'тест', 'контроль'],
          `**Мини-проверка (${title}).** 1) Дай определение одним предложением. 2) Приведи пример. 3) Назови типичную ошибку. 4) Свяжи с предыдущей темой раздела «${topic.title}».`,
          `Drill for ${title}: define → example → mistake → link.`,
        ),
      )
    }
  }
}

// --- 3) Элементы ---
const profiles = readJson('src/data/elementRealLife/elementRealLifeProfiles.json')
const periodic = readJson('src/data/periodicTableRaw.json')
const elements = Array.isArray(periodic) ? periodic : periodic.elements || periodic

function elName(el) {
  return el.nameRu || el.name || el.symbol
}

for (const el of elements) {
  const z = el.z || el.number || el.atomicNumber
  if (!z) continue
  const symbol = el.symbol
  const name = elName(el)
  const nameEn = el.name || el.nameEn || symbol
  const prof = profiles.find((p) => p.z === z)
  const mass = el.atomicMass || el.atomic_mass || '—'
  const ox = el.oxidationStates || el.oxidation_states || '—'
  const conf = el.electronConfiguration || el.electron_configuration || '—'
  const block = el.groupBlock || el.category || ''
  const state = el.standardState || el.phase || ''
  const group = el.group || el.groupBlock || ''
  const period = el.period || ''

  push(
    chunk(
      `mega-el-${z}-core`,
      `${name} (${symbol}) — карточка элемента`,
      [7, 8, 9],
      [name, symbol, nameEn, `элемент ${z}`, 'периодическ', 'менделеев'],
      `**${name}** (${symbol}, №${z}). Атомная масса ≈ ${mass}. Категория: ${block || '—'}. Состояние: ${state || '—'}. Конфигурация: ${conf}. Степени окисления: ${ox}.`,
      `${nameEn} (${symbol}, #${z}). Mass ≈ ${mass}. ${block}. Ox: ${ox}.`,
    ),
  )
  push(
    chunk(
      `mega-el-${z}-pos`,
      `${name}: положение в таблице`,
      [7, 8, 9],
      [name, symbol, 'группа', 'период', 'таблица'],
      `**Где стоит ${name} (${symbol})?** №${z}${period ? `, период ${period}` : ''}${group ? `, группа/блок: ${group}` : ''}. Тип: ${block || 'см. таблицу'}.`,
      `${nameEn} position: Z=${z}, period ${period}, ${block}.`,
    ),
  )
  push(
    chunk(
      `mega-el-${z}-ask`,
      `Вопрос: что за элемент ${symbol}`,
      [7, 8, 9],
      [name, symbol, 'что такое', 'элемент', 'контрольная'],
      `**Вопрос:** что такое ${name} / ${symbol}?\n**Ответ:** элемент №${z}, символ ${symbol}, масса ≈ ${mass}. Класс: ${block || '—'}. Степени окисления: ${ox}.`,
      `What is ${symbol}? Element #${z}, ${nameEn}.`,
    ),
  )

  if (prof?.usesRu?.length) {
    push(
      chunk(
        `mega-el-${z}-uses`,
        `${name}: применение`,
        [7, 8, 9, 10],
        [name, symbol, 'применен', 'где используют'],
        `**Где применяют ${name} (${symbol})?** ${(prof.usesRu || []).slice(0, 6).join('; ')}.`,
        `Uses of ${nameEn}: ${(prof.usesRu || []).slice(0, 4).join('; ')}.`,
      ),
    )
  }
  if (prof?.extractionRu) {
    push(
      chunk(
        `mega-el-${z}-get`,
        `${name}: получение`,
        [8, 9, 10],
        [name, symbol, 'получен', 'как получить'],
        `**Как получают ${name}?** ${prof.extractionRu}`,
        `How ${nameEn} is obtained: ${String(prof.extractionRu).slice(0, 240)}`,
      ),
    )
  }
  if (ox && ox !== '—') {
    push(
      chunk(
        `mega-el-${z}-ox`,
        `${name}: степени окисления`,
        [8, 9, 10],
        [name, symbol, 'степень окислен', 'валент'],
        `У **${name} (${symbol})** степени окисления: ${ox}. В задачах начинайте с типичных (O −2, H +1).`,
        `${nameEn} oxidation states: ${ox}.`,
      ),
    )
  }
  push(
    chunk(
      `mega-el-${z}-school`,
      `${name}: что спрашивают в школе`,
      [7, 8, 9],
      [name, symbol, 'контрольная', 'огэ', 'вопрос'],
      `Школьный минимум по **${name} (${symbol})**: №${z}, тип (${block || 'см. группу'}), типичные соединения и роль в реакциях.`,
      `School focus for ${nameEn}: Z=${z}, category, compounds.`,
    ),
  )
  if (conf && conf !== '—') {
    push(
      chunk(
        `mega-el-${z}-econf`,
        `${name}: электронная конфигурация`,
        [8, 9, 10],
        [name, symbol, 'электронн', 'конфигурац', 'уровен'],
        `**Электронная конфигурация ${name} (${symbol}).** ${conf}. Химию определяют внешние электроны.`,
        `${nameEn} config: ${conf}.`,
      ),
    )
  }
}

