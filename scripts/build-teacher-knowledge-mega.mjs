#!/usr/bin/env node
/**
 * Собирает мега-базу знаний ИИ-учителя (~10× к текущему индексу).
 * Источники: учебники g7–g9, профили элементов, шаблоны теории 7–11.
 *
 * Запуск: node scripts/build-teacher-knowledge-mega.mjs
 * Выход: src/data/teacherKnowledge/megaPack.json
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const OUT_DIR = path.join(ROOT, 'src', 'data', 'teacherKnowledge')
const OUT_FILE = path.join(OUT_DIR, 'megaPack.json')

function readJson(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'))
}

function chunk(id, topic, grades, keywords, ru, en) {
  return {
    id,
    topic,
    grades,
    keywords: [...new Set(keywords.map((k) => String(k).toLowerCase()).filter((k) => k.length >= 2))],
    ru,
    en,
  }
}

function splitParagraphs(text, maxLen = 420) {
  const raw = String(text || '')
    .replace(/\r/g, '')
    .split(/\n{2,}|(?<=\.)\s+(?=[А-ЯA-Z«"0-9])/)
    .map((s) => s.replace(/\s+/g, ' ').trim())
    .filter((s) => s.length >= 40)
  const out = []
  let buf = ''
  for (const p of raw) {
    if ((buf + ' ' + p).trim().length <= maxLen) buf = (buf + ' ' + p).trim()
    else {
      if (buf) out.push(buf)
      buf = p.slice(0, maxLen)
    }
  }
  if (buf) out.push(buf)
  return out.length ? out : raw.slice(0, 8)
}

const chunks = []

// --- 1) Учебники: микро-чанки по параграфам / определениям / ragParts ---
for (const grade of ['g7', 'g8', 'g9']) {
  const gradeNum = Number(grade.slice(1))
  const data = readJson(`src/data/${grade}TextbookKnowledge.json`)
  const sections = data.sections || data
  for (const sec of sections) {
    const topicRu = sec.topicRu || sec.titleRu || sec.topic || 'Тема'
    const topicEn = sec.topicEn || sec.titleEn || topicRu
    const sid = sec.id || `${sec.chapterId}-${sec.sectionId}`
    const baseKw = [
      topicRu,
      ...(sec.keywords || []).slice(0, 24),
      grade,
      sec.chapterId,
      sec.sectionId,
      ...(sec.conceptsRu || []),
    ].filter(Boolean)

    const bodies = []
    if (Array.isArray(sec.ragParts)) {
      for (const p of sec.ragParts) {
        if (typeof p === 'string' && p.trim()) bodies.push(p.trim())
        else if (p?.ru) bodies.push(String(p.ru))
        else if (p?.textRu) bodies.push(String(p.textRu))
      }
    }
    if (sec.contentRu) bodies.push(String(sec.contentRu))
    if (Array.isArray(sec.definitionsRu)) {
      sec.definitionsRu.forEach((d, i) => {
        if (!d || String(d).length < 20) return
        chunks.push(
          chunk(
            `${sid}-def-${i}`,
            `Определение: ${topicRu}`,
            [gradeNum],
            [...baseKw, 'определен', 'что такое'],
            `**${topicRu}** (кл. ${gradeNum}, определение).\n${String(d).replace(/\s+/g, ' ').trim()}`,
            `**${topicEn}** definition: ${String(d).replace(/\s+/g, ' ').trim().slice(0, 400)}`,
          ),
        )
      })
    }
    if (Array.isArray(sec.conceptsRu)) {
      sec.conceptsRu.forEach((c, i) => {
        chunks.push(
          chunk(
            `${sid}-concept-${i}`,
            `Понятие: ${c}`,
            [gradeNum],
            [...baseKw, c, 'понятие', 'термин'],
            `**Ключевое понятие (§ ${topicRu}).** ${c}. Изучается в ${gradeNum} классе, раздел «${topicRu}».`,
            `Key concept in ${topicEn}: ${c}.`,
          ),
        )
      })
    }

    const joined = bodies.join('\n\n')
    const parts = splitParagraphs(joined, 320)
    parts.forEach((part, i) => {
      chunks.push(
        chunk(
          `${sid}-p-${i}`,
          `${topicRu} (§${i + 1})`,
          [gradeNum],
          [
            ...baseKw,
            ...(part.toLowerCase().match(/[а-яёa-z0-9-]{4,}/gi) || []).slice(0, 10),
          ],
          `**${topicRu}** (класс ${gradeNum}, стр. ${sec.page || '—'}).\n${part}`,
          `**${topicEn}** (grade ${gradeNum}). ${String(sec.contentEn || topicEn).slice(0, 360)}`,
        ),
      )
    })

    // Скользящие окна отключены: дублируют textbookKnowledgeChunks и засоряют RAG.
    // Параграфные срезы (-p-*) + remember/defs достаточно.

    const remember = sec.rememberRu || ''
    if (remember) {
      chunks.push(
        chunk(
          `${sid}-remember`,
          `Запомните: ${topicRu}`,
          [gradeNum],
          [...baseKw, 'запомните', 'итог', 'вывод'],
          `**Краткий итог (${topicRu}).** ${String(remember).replace(/\s+/g, ' ').trim()}`,
          `Key takeaway (${topicEn}): ${String(sec.rememberEn || remember).slice(0, 500)}`,
        ),
      )
    }
  }
}

// --- 2) Элементы: несколько карточек на каждый Z ---
const profiles = readJson('src/data/elementRealLife/elementRealLifeProfiles.json')
const periodic = readJson('src/data/periodicTableRaw.json')
const elements = Array.isArray(periodic) ? periodic : periodic.elements || periodic

function elName(el) {
  return el.nameRu || el.name || el.symbol
}

for (const el of elements) {
  const z = el.z || el.number || el.atomicNumber
  if (!z) continue
  const symbol = el.symbol
  const name = elName(el)
  const nameEn = el.name || el.nameEn || symbol
  const prof = profiles.find((p) => p.z === z)
  const mass = el.atomicMass || el.atomic_mass || '—'
  const ox = el.oxidationStates || el.oxidation_states || '—'
  const conf = el.electronConfiguration || el.electron_configuration || '—'
  const block = el.groupBlock || el.category || ''
  const state = el.standardState || el.phase || ''

  chunks.push(
    chunk(
      `mega-el-${z}-core`,
      `${name} (${symbol}) — карточка элемента`,
      [7, 8, 9],
      [name, symbol, nameEn, `элемент ${z}`, 'периодическ', 'менделеев'],
      `**${name}** (${symbol}, №${z}). Атомная масса ≈ ${mass}. Категория: ${block || '—'}. Состояние: ${state || '—'}. Электронная конфигурация: ${conf}. Степени окисления: ${ox}.`,
      `**${nameEn}** (${symbol}, #${z}). Mass ≈ ${mass}. Category: ${block}. State: ${state}. Config: ${conf}. Oxidation: ${ox}.`,
    ),
  )

  if (prof?.usesRu?.length) {
    chunks.push(
      chunk(
        `mega-el-${z}-uses`,
        `${name}: применение`,
        [7, 8, 9, 10],
        [name, symbol, 'применен', 'где используют', 'зачем'],
        `**Где применяют ${name} (${symbol})?** ${(prof.usesRu || []).slice(0, 6).join('; ')}.${prof.appearanceRu ? ` Внешний вид/свойства: ${prof.appearanceRu}` : ''}`,
        `Uses of ${nameEn}: ${(prof.usesRu || []).slice(0, 4).join('; ')}.`,
      ),
    )
  }

  if (prof?.extractionRu) {
    chunks.push(
      chunk(
        `mega-el-${z}-get`,
        `${name}: получение`,
        [8, 9, 10],
        [name, symbol, 'получен', 'как получить', 'добыч', 'промышлен'],
        `**Как получают ${name}?** ${prof.extractionRu}`,
        `How ${nameEn} is obtained: ${prof.extractionRu}`,
      ),
    )
  }

  if (ox && ox !== '—') {
    chunks.push(
      chunk(
        `mega-el-${z}-ox`,
        `${name}: степени окисления`,
        [8, 9, 10],
        [name, symbol, 'степень окислен', 'валент', 'окислит'],
        `У **${name} (${symbol})** степени окисления: ${ox}. В задачах на ОВР и формулы начинайте с типичных значений (O −2, H +1, металлы групп 1–2 — +1/+2).`,
        `${nameEn} oxidation states: ${ox}.`,
      ),
    )
  }

  chunks.push(
    chunk(
      `mega-el-${z}-school`,
      `${name}: что спрашивают в школе`,
      [7, 8, 9],
      [name, symbol, 'контрольная', 'огэ', 'егэ', 'вопрос'],
      `Школьный минимум по **${name} (${symbol})**: положение в таблице (№${z}), тип элемента (${block || 'см. группу'}), типичные соединения и роль в реакциях. Если спрашивают «что это» — начните с номера, символа и класса (металл/неметалл).`,
      `School focus for ${nameEn}: Z=${z}, category, typical compounds.`,
    ),
  )
}

