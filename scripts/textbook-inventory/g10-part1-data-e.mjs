/** Реакция раздела по уравнению (и странице): opts дополняются. */
function edit(id, page, equation, opts = {}, patch = {}) {
  const rx = sections[id]?.rx;
  if (!rx) throw new Error(`g10-part1-data-e: нет раздела ${id}`);
  const r = rx.find((t) => t[0] === page && t[2] === equation);
  if (!r) throw new Error(`g10-part1-data-e: ${id} с. ${page}: нет реакции «${equation}»`);
  if (patch.equation) r[2] = patch.equation;
  if (patch.asInBook !== undefined) r[1] = patch.asInBook;
  if (patch.type) r[3] = patch.type;
  if (patch.cond !== undefined) r[4] = patch.cond;
  r[6] = { ...(r[6] ?? {}), ...opts };
}
const add = (id, ...list) => {
  if (!sections[id]) throw new Error(`g10-part1-data-e: нет раздела ${id}`);
  sections[id].rx.push(...list);
  sections[id].rx.sort((a, b) => a[0] - b[0]);
};

